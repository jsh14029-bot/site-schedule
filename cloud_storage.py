"""Shared PostgreSQL storage, with explicit opt-in local SQLite mode.

This adapter covers the SQL used by app.py and kakao_sync.py. It is not a
general-purpose SQLite emulator. Never fall back to SQLite on a cloud error.
"""
import os
import sqlite3
from pathlib import Path
from threading import Lock


_schema_lock = Lock()
_schema_ready = set()
_schema_version = 1


class StorageError(RuntimeError):
    pass


TEXT_COLUMNS = [
    "schedule_date", "schedule_time", "category", "title", "company",
    "quantity", "location", "memo", "specification", "person", "participants",
    "end_time", "vehicle_count", "deleted_at",
]


class Record(dict):
    """Keep both sqlite3.Row access styles used by the existing application."""
    def __getitem__(self, key):
        if isinstance(key, (int, slice)):
            return tuple(self.values())[key]
        return super().__getitem__(key)


def record_factory(cursor):
    names = [column.name for column in (cursor.description or [])]
    return lambda values: Record(zip(names, values))


class PostgresConnection:
    is_postgres = True

    def __init__(self, config):
        import psycopg
        self._transactions = []
        options = {
            "connect_timeout": 15, "sslmode": "require",
            "autocommit": True, "prepare_threshold": None,
            "row_factory": record_factory,
        }
        if config.get("url"):
            self.raw = psycopg.connect(config["url"], **options)
        else:
            self.raw = psycopg.connect(
                host=config["host"], port=int(config.get("port", 5432)),
                dbname=config.get("dbname", "postgres"), user=config["user"],
                password=config["password"], **options,
            )

    def execute(self, sql, params=()):
        import psycopg
        try:
            # The importer requests an SQLite write lock inside its transaction.
            if sql.strip().upper() == "BEGIN IMMEDIATE":
                sql = "SELECT pg_advisory_xact_lock(17304131)"
            else:
                sql = sql.replace("?", "%s")
            returning_id = sql.lstrip().upper().startswith("INSERT INTO SCHEDULES (")
            if returning_id:
                sql += " RETURNING id"
            cursor = self.raw.execute(sql, params or None)
            return Result(cursor, returning_id)
        except psycopg.Error as error:
            # Do not expose connection strings or entered schedule text in the UI.
            raise StorageError("공용 DB 작업에 실패했습니다. 변경사항은 저장되지 않았습니다.") from error

    def executemany(self, sql, parameters):
        import psycopg
        try:
            with self.raw.cursor() as cursor:
                cursor.executemany(sql.replace("?", "%s"), parameters)
        except psycopg.Error as error:
            raise StorageError("공용 DB 작업에 실패했습니다.") from error

    def __enter__(self):
        transaction = self.raw.transaction()
        transaction.__enter__()
        self._transactions.append(transaction)
        return self

    def __exit__(self, *args):
        import psycopg
        try:
            return self._transactions.pop().__exit__(*args)
        except psycopg.Error as error:
            raise StorageError("DB 저장 확정에 실패했습니다. 저장 여부를 확인한 후 다시 시도하세요.") from error

    def close(self):
        self.raw.close()


class Result:
    def __init__(self, cursor, returning_id=False):
        self.cursor = cursor
        self.lastrowid = None
        if returning_id:
            self.lastrowid = cursor.fetchone()["id"]

    def fetchone(self):
        return self.cursor.fetchone()

    def fetchall(self):
        return self.cursor.fetchall()

    def __iter__(self):
        return iter(self.cursor)


def migrate_postgres(connection, force=False):
    # Only schema readiness is cached. Schedule reads and writes always reach DB.
    info = connection.raw.info
    key = (info.host, info.port, info.dbname, info.user, _schema_version)
    with _schema_lock:
        if key in _schema_ready and not force:
            return
        statements = [
            "SELECT pg_advisory_xact_lock(17304131)",
            """CREATE TABLE IF NOT EXISTS schedules (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            schedule_date TEXT NOT NULL, title TEXT NOT NULL
        )""",
        ]
        for column in TEXT_COLUMNS:
            statements.append(f"ALTER TABLE schedules ADD COLUMN IF NOT EXISTS {column} TEXT")
        statements.append("ALTER TABLE schedules ADD COLUMN IF NOT EXISTS completed INTEGER NOT NULL DEFAULT 0")
        statements.append("""CREATE TABLE IF NOT EXISTS schedule_imports (
            source_key TEXT PRIMARY KEY, schedule_id BIGINT NOT NULL,
            source TEXT NOT NULL, imported_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
        )""")
        statements.append("""CREATE TABLE IF NOT EXISTS sqlite_migration_records (
            source_name TEXT NOT NULL, source_id BIGINT NOT NULL,
            schedule_id BIGINT NOT NULL, PRIMARY KEY (source_name, source_id)
        )""")
        # Browser clients cannot bypass the app through the Supabase Data API.
        for table in ("schedules", "schedule_imports", "sqlite_migration_records"):
            statements.append(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        # Constant DDL only: one network request instead of 22 round trips.
        with connection:
            connection.execute(";\n".join(statements))
        # A failed migration is never marked ready, so a later run can retry.
        _schema_ready.add(key)


def storage_config():
    import streamlit as st
    try:
        config = dict(st.secrets.get("storage", {}))
    except FileNotFoundError:
        config = {}
    if os.environ.get("DATABASE_URL"):
        config["url"] = os.environ["DATABASE_URL"]
    if os.environ.get("SCHEDULE_STORAGE_MODE"):
        config["mode"] = os.environ["SCHEDULE_STORAGE_MODE"]
    return config


def open_database(config=None):
    config = storage_config() if config is None else dict(config)
    mode = config.get("mode", "postgres")
    if mode == "sqlite":
        path = Path(config.get("sqlite_path", Path(__file__).resolve().parent / "schedule.db"))
        connection = sqlite3.connect(str(path), timeout=30)
        connection.row_factory = sqlite3.Row
        return connection
    if mode != "postgres":
        raise StorageError("storage.mode는 postgres 또는 sqlite여야 합니다.")
    if not config.get("url") and not all(config.get(key) for key in ("host", "user", "password")):
        raise StorageError("공용 DB 설정이 필요합니다. Manage app → Settings → Secrets에 [storage] 설정을 입력하세요.")
    try:
        return PostgresConnection(config)
    except (ImportError, ValueError, KeyError):
        raise StorageError("DB 설정 또는 psycopg 설치를 확인하세요.") from None
    except Exception:
        raise StorageError("공용 DB에 연결하지 못했습니다. 설정과 Supabase 프로젝트 상태를 확인하세요. 임시 DB로 저장하지 않습니다.") from None


def import_sqlite(source_path, target, source_name):
    """Read-only source; transactional import. Same source name + id is imported once."""
    if not source_name.strip():
        raise ValueError("이전 출처 이름이 필요합니다.")
    path = Path(source_path).resolve()
    source = sqlite3.connect(path.as_uri() + "?mode=ro", uri=True)
    source.row_factory = sqlite3.Row
    try:
        columns = {row[1] for row in source.execute("PRAGMA table_info(schedules)")}
        if not {"id", "schedule_date", "title"} <= columns:
            raise ValueError("일정관리 DB 파일이 아닙니다.")
        rows = source.execute("SELECT * FROM schedules ORDER BY id").fetchall()
        imports_exist = source.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='schedule_imports'").fetchone()
        old_imports = source.execute("SELECT source_key, schedule_id, source, imported_at FROM schedule_imports").fetchall() if imports_exist else []
        inserted = 0
        with target:
            target.execute("SELECT pg_advisory_xact_lock(17304131)")
            id_map = {}
            for row in rows:
                known = target.execute("SELECT schedule_id FROM sqlite_migration_records WHERE source_name = ? AND source_id = ?", (source_name, row["id"])).fetchone()
                if known:
                    id_map[row["id"]] = known[0]
                    continue
                keys = [key for key in TEXT_COLUMNS + ["completed"] if key in columns]
                cursor = target.execute("INSERT INTO schedules (" + ",".join(keys) + ") VALUES (" + ",".join("?" for _ in keys) + ")", [row[key] for key in keys])
                new_id = cursor.lastrowid
                target.execute("INSERT INTO sqlite_migration_records (source_name, source_id, schedule_id) VALUES (?, ?, ?)", (source_name, row["id"], new_id))
                id_map[row["id"]] = new_id
                inserted += 1
            for row in old_imports:
                if row["schedule_id"] in id_map:
                    target.execute("INSERT INTO schedule_imports (source_key, schedule_id, source, imported_at) VALUES (?, ?, ?, ?) ON CONFLICT (source_key) DO NOTHING", (row["source_key"], id_map[row["schedule_id"]], row["source"], row["imported_at"]))
        return {"inserted": inserted, "skipped": len(rows) - inserted}
    finally:
        source.close()


if __name__ == "__main__":
    import argparse
    import tomllib
    parser = argparse.ArgumentParser(description="기존 SQLite 일정을 Supabase로 한 번 이전합니다. 원본 DB는 변경하지 않습니다.")
    parser.add_argument("database", type=Path)
    parser.add_argument("--source-name", required=True, help="같은 원본은 재시도할 때도 같은 이름 사용")
    parser.add_argument("--secrets", type=Path, default=Path(".streamlit/secrets.toml"))
    args = parser.parse_args()
    settings = tomllib.loads(args.secrets.read_text(encoding="utf-8-sig"))["storage"]
    if settings.get("mode", "postgres") != "postgres":
        parser.error("대상은 postgres여야 합니다.")
    connection = open_database(settings)
    try:
        migrate_postgres(connection)
        print(import_sqlite(args.database, connection, args.source_name))
    finally:
        connection.close()
